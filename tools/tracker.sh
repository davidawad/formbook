#!/bin/sh
# Regenerate the tracker: manifest (shell) -> completion logic (Bend) -> README block, STATUS.md, per-folder READMEs.
# Usage: tools/tracker.sh        (needs: bend, jq, python3)
set -eu
ROOT=$(cd "$(dirname "$0")/.." && pwd)
cd "$ROOT"
mkdir -p out

sh tools/manifest.sh > out/manifest.txt

# Bend prints three sections ("=== summary|status|rows"); a failed run exits nonzero.
if ! bend tools/tracker.bend out/manifest.txt > out/tracker.out 2> out/bend.err; then
  cat out/bend.err >&2
  exit 1
fi
section() { awk -v s="=== $1" '/^=== /{on = ($0 == s); next} on' out/tracker.out; }
section summary > out/summary.md
section status  > out/status.md
section rows    > out/rows.txt

# splice the summary into README.md between the tracker markers
awk -v f=out/summary.md '
  /<!-- tracker:start -->/ { print; while ((getline l < f) > 0) print l; skip = 1; next }
  /<!-- tracker:end -->/   { skip = 0 }
  !skip
' README.md > out/README.new
cat out/README.new > README.md

{
  printf '# Status\n\nGenerated by `tools/tracker.sh` (completion logic in `tools/tracker.bend`). Do not edit.\n\n'
  printf '## Summary\n\n'
  cat out/summary.md
  printf '\n## Per court\n\n'
  cat out/status.md
  printf '\n'
} > STATUS.md

python3 tools/gen_readmes.py out/manifest.txt out/rows.txt
