//! `fb tracker`: regenerate the tracker. Manifest -> completion logic (tracker module) -> README block,
//! STATUS.md, per-folder READMEs. Intermediate files go to out/ as before.
use crate::{fail, manifest, readmes, tracker, Res};
use std::fs;
use std::path::Path;
use std::process::ExitCode;

const DOCTYPE_INTRO: &str = "\nTypst per doc type (a doc type is complete with template, sample, render and exemplar; it is up for review when its typst eval passes; per-doc-type rows in STATUS.md):\n\n";

pub fn main(args: &[String]) -> Res<ExitCode> {
    match args {
        [] => run(&crate::repo_root()?),
        [arg] if arg == "--check" => check(&crate::repo_root()?),
        _ => Err(fail(2, "usage: fb tracker [--check]")),
    }
}

/// Recompute the two committed root tracker files without writing any generated files.
fn check(root: &Path) -> Res<ExitCode> {
    let man = manifest::court_lines(root)?;
    let dts = manifest::doctype_lines(root)?;
    let s = tracker::compute(&man, &dts);
    let block = format!("{}{DOCTYPE_INTRO}{}", s.summary, s.dsummary);
    let readme_path = root.join("README.md");
    let current_readme = fs::read_to_string(&readme_path).map_err(|e| io_fail(&readme_path, e))?;
    let readme = current_readme.replace("\r\n", "\n").replace('\r', "\n");
    let expected_readme =
        readmes::root_index(root, &man, &s.rows, &s.docrows, &splice(&readme, &block))?;
    let status_path = root.join("STATUS.md");
    let expected_status = status_md(&s);
    let current_status = fs::read_to_string(&status_path).map_err(|e| io_fail(&status_path, e))?;
    let stale = [
        ("README.md", current_readme != expected_readme),
        ("STATUS.md", current_status != expected_status),
    ]
    .into_iter()
    .filter_map(|(name, differs)| differs.then_some(name))
    .collect::<Vec<_>>();
    if stale.is_empty() {
        println!("RESULT: TRACKER CHECK PASS");
        Ok(ExitCode::SUCCESS)
    } else {
        println!("RESULT: TRACKER CHECK FAIL: stale {}", stale.join(", "));
        println!("Run `tools/tracker.sh` to regenerate the tracker files.");
        Ok(ExitCode::from(1))
    }
}

fn run(root: &Path) -> Res<ExitCode> {
    let out = root.join("out");
    fs::create_dir_all(&out).map_err(|e| io_fail(&out, e))?;
    let man = manifest::court_lines(root)?;
    let dts = manifest::doctype_lines(root)?;
    let s = tracker::compute(&man, &dts);
    let block = format!("{}{DOCTYPE_INTRO}{}", s.summary, s.dsummary);
    [
        ("manifest.txt", man.as_str()),
        ("doctypes.txt", dts.as_str()),
        ("summary.md", s.summary.as_str()),
        ("status.md", s.status.as_str()),
        ("rows.txt", s.rows.as_str()),
        ("dsummary.md", s.dsummary.as_str()),
        ("doctypes.md", s.doctypes.as_str()),
        ("readme-block.md", block.as_str()),
    ]
    .iter()
    .try_for_each(|(name, text)| write(&out.join(name), text))?;
    let readme = root.join("README.md");
    let current = fs::read_to_string(&readme).map_err(|e| io_fail(&readme, e))?;
    write(&readme, &splice(&current, &block))?;
    write(&root.join("STATUS.md"), &status_md(&s))?;
    println!("{}", readmes::write_all(root, &man, &s.rows, &s.docrows)?);
    Ok(ExitCode::SUCCESS)
}

/// The awk splice: every line is kept, except those after a line containing the start marker and before
/// the next line containing the end marker; the block follows the (first) start marker line.
pub fn splice(text: &str, block: &str) -> String {
    let (out, _, _) = records(text).fold(
        (String::new(), false, false),
        |(mut acc, skip, used), line| {
            if line.contains("<!-- tracker:start -->") {
                acc.push_str(line);
                acc.push('\n');
                records(if used { "" } else { block }).for_each(|l| {
                    acc.push_str(l);
                    acc.push('\n');
                });
                (acc, true, true)
            } else {
                let skip = skip && !line.contains("<!-- tracker:end -->");
                if !skip {
                    acc.push_str(line);
                    acc.push('\n');
                }
                (acc, skip, used)
            }
        },
    );
    out
}

/// awk records: lines split on newline; a final line without one still counts.
fn records(text: &str) -> impl Iterator<Item = &str> {
    text.strip_suffix('\n')
        .unwrap_or(text)
        .split('\n')
        .filter(move |_| !text.is_empty())
}

fn status_md(s: &tracker::Sections) -> String {
    [
        "# Status\n\nGenerated by `tools/tracker.sh` (completion logic in `tools/fb`). Do not edit.\n\n",
        "## Summary\n\n",
        &s.summary,
        "\n## Per court\n\n",
        &s.status,
        "\n## Typst per doc type: summary\n\n",
        "One row per doc-type folder (`COURT/<doctype>/`), plus the court folder itself as \"(court root)\" when it has its own `typst/main.typ`. ",
        "Complete = all four present, each keyed on committed text so a checkout without PDFs counts the same: Typst template (`typst/main.typ`), sample (`usage/INPUT-<doctype>[-<n>].md`), render (template and sample committed), ",
        "exemplar (a `FILED-EXAMPLE-<doctype>[-<n>].pdf` named in `usage/SOURCE.md`). Overlays are generated on demand into `.overlay/` and are not counted. Status: **up for review** = `fb check` (court checks.yaml, else the default set in `data/checks-default.yaml`) left a valid typst stamp for the folder (`just eval` re-runs it); **in progress** = something is present; **todo** = nothing. A court is up for review when it has `rules.md` and every doc folder under it with an INPUT is up for review. `done` is set by hand in `court.json`.\n\n",
        &s.dsummary,
        "\n## Typst per doc type\n\n",
        &s.doctypes,
        "\n",
    ]
    .concat()
}

pub fn write(p: &Path, text: &str) -> Res<()> {
    fs::write(p, text).map_err(|e| io_fail(p, e))
}

pub fn io_fail(p: &Path, e: std::io::Error) -> crate::Fail {
    fail(1, format!("{}: {e}", p.display()))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn splice_replaces_between_markers() {
        let readme = "a\n<!-- tracker:start -->\nold\nold2\n<!-- tracker:end -->\nb";
        assert_eq!(
            splice(readme, "X\nY\n"),
            "a\n<!-- tracker:start -->\nX\nY\n<!-- tracker:end -->\nb\n"
        );
    }

    #[test]
    fn splice_without_end_drops_the_rest() {
        assert_eq!(
            splice("a\n<!-- tracker:start -->\nz\n", "X\n"),
            "a\n<!-- tracker:start -->\nX\n"
        );
    }

    #[test]
    fn splice_block_only_once() {
        let readme = "<!-- tracker:start -->\n<!-- tracker:end -->\n<!-- tracker:start -->\nq\n<!-- tracker:end -->\n";
        assert_eq!(
            splice(readme, "X\n"),
            "<!-- tracker:start -->\nX\n<!-- tracker:end -->\n<!-- tracker:start -->\n<!-- tracker:end -->\n"
        );
    }

    #[test]
    fn splice_no_markers_keeps_text() {
        assert_eq!(splice("", "X\n"), "");
        assert_eq!(splice("a\nb\n", "X\n"), "a\nb\n");
    }
}
