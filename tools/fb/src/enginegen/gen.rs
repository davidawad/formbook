//! `fb engines gen <doc-folder> [--check]`: the latex and docx engines of a folder on the shared document model
//! (fb-595.54.12), generated from its typst template's face and its `typst/layout.yaml`.
//!
//! A folder is on the model when its typst template sets `xdoc(yaml("layout.yaml") + (font: ..), meta, body)`
//! (lib/typst/xdoc.typ). The layout is the single source of every number; the generator writes:
//!   latex/template.tex   the preamble: the face's LaTeX package (one face, docs/EVAL-LOOP.md step 0), the page
//!                        (geometry, the page number's line), lib/latex/xengine.sty, the body and footnote line
//!                        boxes, the footnote rule and marks, the lists; `$body$` is lib/latex/xdoc.lua's
//!   latex/xdoc.lua       `return require("latex.xdoc")(<layout>)`
//!   docx/reference.xml   the cross-engine recipe at the layout's sizes and pitches (`{font}`: the typst face),
//!                        the styles lib/docx/xdoc.lua names, the page-number footer and the section
//!   docx/xdoc.lua        `return require("docx.xdoc")(<layout>)`
//! Every file says it is generated; `--check` writes nothing and fails when one differs from what it would write.
use crate::{fail, Res};
use serde_yaml::Value;
use std::path::Path;

/// The generated files of a folder: (path relative to the folder, contents).
pub type Files = Vec<(String, String)>;

pub const HEAD: &str =
    "Generated by `fb engines gen` (tools/fb/src/enginegen/gen.rs) from typst/layout.yaml and the \
typst template's face (fb-595.54.12): do not edit, change the layout and generate again.";

/// A number of the layout at a dotted path, or `default`.
pub fn num(l: &Value, path: &str, default: Option<f64>) -> Result<f64, String> {
    let mut v = l;
    for k in path.split('.') {
        match v.get(k) {
            Some(x) => v = x,
            None => return default.ok_or_else(|| format!("layout.yaml: `{path}` is required")),
        }
    }
    v.as_f64()
        .ok_or_else(|| format!("layout.yaml: `{path}` is not a number"))
}

/// Points as a short decimal (no trailing zeros).
pub fn fmt(x: f64) -> String {
    let s = format!("{:.4}", x);
    let s = s.trim_end_matches('0').trim_end_matches('.');
    if s == "-0" {
        "0".into()
    } else {
        s.into()
    }
}

/// Points as twips (Word's twentieths of a point); the layout keeps every length a whole number of them.
pub fn twips(x: f64, what: &str) -> Result<i64, String> {
    let t = x * 20.0;
    if (t - t.round()).abs() > 1e-6 {
        return Err(format!(
            "layout.yaml: `{what}` = {} pt is not a whole number of twips (1/20 pt): Word cannot set it",
            fmt(x)
        ));
    }
    Ok(t.round() as i64)
}

/// Every length of the layout is a whole number of twips (sizes: half points).
pub fn validate(l: &Value, path: &str, errs: &mut Vec<String>) {
    match l {
        Value::Mapping(m) => {
            for (k, v) in m {
                let k = k.as_str().unwrap_or("?");
                let p = if path.is_empty() {
                    k.to_string()
                } else {
                    format!("{path}.{k}")
                };
                validate(v, &p, errs);
            }
        }
        Value::Sequence(s) => {
            for (i, v) in s.iter().enumerate() {
                validate(v, &format!("{path}[{i}]"), errs);
            }
        }
        Value::Number(n) => {
            let x = n.as_f64().unwrap_or(0.0);
            let leaf = path.rsplit('.').next().unwrap_or("");
            if leaf == "size" || leaf == "from" {
                if (x * 2.0 - (x * 2.0).round()).abs() > 1e-9 {
                    errs.push(format!(
                        "layout.yaml: `{path}` = {x}: sizes are whole half points"
                    ));
                }
            } else if let Err(e) = twips(x, path) {
                errs.push(e);
            }
        }
        _ => {}
    }
}

/// A Lua literal of a YAML value (maps keep their order; null is nil).
pub fn lua(v: &Value, indent: usize) -> String {
    let pad = "  ".repeat(indent + 1);
    let end = "  ".repeat(indent);
    match v {
        Value::Null => "nil".into(),
        Value::Bool(b) => b.to_string(),
        Value::Number(n) => n.as_f64().map(fmt).unwrap_or_else(|| n.to_string()),
        Value::String(s) => lua_str(s),
        Value::Sequence(s) if s.is_empty() => "{}".into(),
        Value::Sequence(s) => {
            let items: Vec<String> = s
                .iter()
                .map(|x| format!("{pad}{},", lua(x, indent + 1)))
                .collect();
            format!("{{\n{}\n{end}}}", items.join("\n"))
        }
        Value::Mapping(m) if m.is_empty() => "{}".into(),
        Value::Mapping(m) => {
            let items: Vec<String> = m
                .iter()
                .filter(|(_, x)| !x.is_null())
                .map(|(k, x)| {
                    let k = k.as_str().unwrap_or("?");
                    format!("{pad}[{}] = {},", lua_str(k), lua(x, indent + 1))
                })
                .collect();
            format!("{{\n{}\n{end}}}", items.join("\n"))
        }
        Value::Tagged(t) => lua(&t.value, indent),
    }
}

fn lua_str(s: &str) -> String {
    let mut o = String::from("\"");
    for c in s.chars() {
        match c {
            '"' => o.push_str("\\\""),
            '\\' => o.push_str("\\\\"),
            '\n' => o.push_str("\\n"),
            c => o.push(c),
        }
    }
    o.push('"');
    o
}

/// The LaTeX packages that set the metrics of a typst face (docs/EVAL-LOOP.md, "Adopting the reference breaker",
/// step 0), and whether its Lua advances module (lib/latex/xeschola.lua) applies.
pub fn latex_face(face: &str) -> Result<(&'static str, bool), String> {
    match face {
        "Times New Roman" | "Liberation Serif" | "TeX Gyre Termes" => {
            Ok(("\\usepackage{newtxtext,newtxmath}", false))
        }
        "TeX Gyre Schola" | "Century Schoolbook" => Ok((
            "\\usepackage{tgschola}\n\\usepackage{xeschola} % lib/latex/xeschola.sty",
            true,
        )),
        "EB Garamond" => Ok(("\\usepackage{ebgaramond}", false)),
        "Gelasio" => Ok(("\\usepackage{gelasio}", false)),
        f => Err(format!(
            "no LaTeX face for `{f}` (one face per template: newtx, tgschola, ebgaramond, gelasio)"
        )),
    }
}

/// The page number's line: its pitch and baseline below the text (typst: footer-descent 30 % of the bottom margin,
/// the number in a single line box), and Word's footer distance (from the page foot to the bottom of that box).
pub fn footer(l: &Value) -> Result<(f64, f64, f64), String> {
    let mb = num(l, "margin.bottom", None)?;
    let ps = num(l, "pitch.single", None)?;
    let skip = 0.3 * mb + 0.8 * ps;
    let dist = 0.7 * mb - ps;
    Ok((ps, skip, dist))
}

/// The generated files of a folder whose template sets `face` and whose layout is `l`.
pub fn generate(l: &Value, face: &str) -> Result<Files, String> {
    let mut errs = Vec::new();
    validate(l, "", &mut errs);
    if !errs.is_empty() {
        return Err(errs.join("\n"));
    }
    let spec = lua(l, 0);
    let latex_lua = format!(
        "-- {HEAD}\n-- The shared document model in LaTeX: lib/latex/xdoc.lua sets this layout.\nreturn require(\"latex.xdoc\")({spec})\n"
    );
    let docx_lua = format!(
        "-- {HEAD}\n-- The shared document model in Word: lib/docx/xdoc.lua sets this layout.\nreturn require(\"docx.xdoc\")({spec})\n"
    );
    Ok(vec![
        ("latex/template.tex".into(), super::tex::template(l, face)?),
        ("latex/xdoc.lua".into(), latex_lua),
        (
            "docx/reference.xml".into(),
            super::word::reference(l, face)?,
        ),
        ("docx/xdoc.lua".into(), docx_lua),
    ])
}

/// The generated files of the doc folder `dir`.
pub fn for_folder(dir: &Path) -> Res<Files> {
    let bad = |m: String| fail(1, format!("fb engines gen: {}: {m}", dir.display()));
    let layout = dir.join("typst/layout.yaml");
    let text = std::fs::read_to_string(&layout).map_err(|e| {
        bad(format!(
            "{}: {e} (not on the shared document model)",
            layout.display()
        ))
    })?;
    let l: Value = serde_yaml::from_str(&text).map_err(|e| bad(format!("layout.yaml: {e}")))?;
    let face = crate::typstface::face(dir)
        .ok_or_else(|| bad("the typst template names no face (#let font-family = ..)".into()))?;
    if super::engines_of(dir).contains(&"docx-sh") {
        return Err(bad(
            "has docx/*.sh (fb-595.68 step 2 owns it): not generated".into(),
        ));
    }
    generate(&l, &face).map_err(bad)
}

pub fn main(args: &[String]) -> Res<std::process::ExitCode> {
    let check = args.iter().any(|a| a == "--check");
    let dirs: Vec<&String> = args.iter().filter(|a| !a.starts_with("--")).collect();
    if dirs.is_empty() {
        return Err(fail(2, "usage: fb engines gen <doc-folder>... [--check]"));
    }
    let mut stale = 0;
    for d in dirs {
        let dir = Path::new(d);
        for (rel, text) in for_folder(dir)? {
            let p = dir.join(&rel);
            let old = std::fs::read_to_string(&p).ok();
            if old.as_deref() == Some(text.as_str()) {
                continue;
            }
            if check {
                println!("STALE {}", p.display());
                stale += 1;
                continue;
            }
            if let Some(parent) = p.parent() {
                std::fs::create_dir_all(parent)
                    .map_err(|e| fail(2, format!("fb engines gen: {}: {e}", parent.display())))?;
            }
            std::fs::write(&p, &text)
                .map_err(|e| fail(2, format!("fb engines gen: {}: {e}", p.display())))?;
            println!("wrote {}", p.display());
        }
    }
    Ok(if stale > 0 {
        std::process::ExitCode::from(1)
    } else {
        std::process::ExitCode::SUCCESS
    })
}
