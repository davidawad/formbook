//! `fb engines gen <doc-folder> [--check]`: the latex and docx engines of a folder on the shared document model
//! (fb-595.54.12), generated from its typst template's face and its `typst/layout.yaml`.
//!
//! A folder is on the model when its typst template sets `xdoc(yaml("layout.yaml") + (font: ..), meta, body)`
//! (lib/typst/xdoc.typ). The layout is the single source of every number; the generator writes:
//!   latex/template.tex   the preamble: the face's LaTeX package (one face, docs/EVAL-LOOP.md step 0), the page
//!                        (geometry, the page number's line), lib/latex/xengine.sty, the body and footnote line
//!                        boxes, the footnote rule and marks, the lists; `$body$` is lib/latex/xdoc.lua's
//!   latex/xdoc.lua       `return require("latex.xdoc")(<layout>)`
//!   docx/reference.xml   the cross-engine recipe at the layout's sizes and pitches (`{font}`: the typst face),
//!                        the styles lib/docx/xdoc.lua names, the page-number footer and the section
//!   docx/xdoc.lua        `return require("docx.xdoc")(<layout>)`
//! Every file says it is generated; `--check` writes nothing and fails when one differs from what it would write.
use crate::{fail, Res};
use serde_yaml::Value;
use std::path::Path;

/// The generated files of a folder: (path relative to the folder, contents).
pub type Files = Vec<(String, String)>;

pub const HEAD: &str =
    "Generated by `fb engines gen` (tools/fb/src/enginegen/gen.rs) from typst/layout.yaml and the \
typst template's face (fb-595.54.12): do not edit, change the layout and generate again.";

/// A number of the layout at a dotted path, or `default`.
pub fn num(l: &Value, path: &str, default: Option<f64>) -> Result<f64, String> {
    let mut v = l;
    for k in path.split('.') {
        match v.get(k) {
            Some(x) => v = x,
            None => return default.ok_or_else(|| format!("layout.yaml: `{path}` is required")),
        }
    }
    v.as_f64()
        .ok_or_else(|| format!("layout.yaml: `{path}` is not a number"))
}

/// Points as a short decimal (no trailing zeros).
pub fn fmt(x: f64) -> String {
    let s = format!("{:.4}", x);
    let s = s.trim_end_matches('0').trim_end_matches('.');
    if s == "-0" {
        "0".into()
    } else {
        s.into()
    }
}

/// Points as twips (Word's twentieths of a point); the layout keeps every length a whole number of them.
pub fn twips(x: f64, what: &str) -> Result<i64, String> {
    let t = x * 20.0;
    if (t - t.round()).abs() > 1e-6 {
        return Err(format!(
            "layout.yaml: `{what}` = {} pt is not a whole number of twips (1/20 pt): Word cannot set it",
            fmt(x)
        ));
    }
    Ok(t.round() as i64)
}

/// Every length of the layout is a whole number of twips (sizes: half points).
pub fn validate(l: &Value, path: &str, errs: &mut Vec<String>) {
    match l {
        Value::Mapping(m) => {
            for (k, v) in m {
                let k = k.as_str().unwrap_or("?");
                let p = if path.is_empty() {
                    k.to_string()
                } else {
                    format!("{path}.{k}")
                };
                validate(v, &p, errs);
            }
        }
        Value::Sequence(s) => {
            for (i, v) in s.iter().enumerate() {
                validate(v, &format!("{path}[{i}]"), errs);
            }
        }
        Value::Number(n) => {
            let x = n.as_f64().unwrap_or(0.0);
            let leaf = path.rsplit('.').next().unwrap_or("");
            if leaf == "latex_bias" {
                // a measured fraction of a point (folder_latex_bias), not a length LaTeX or Word sets on its own
            } else if leaf == "size" || leaf == "from" {
                if (x * 2.0 - (x * 2.0).round()).abs() > 1e-9 {
                    errs.push(format!(
                        "layout.yaml: `{path}` = {x}: sizes are whole half points"
                    ));
                }
            } else if let Err(e) = twips(x, path) {
                errs.push(e);
            }
        }
        _ => {}
    }
}

/// A heading style with a `number` (lib/pandoc/xdoc.lua heading_labels) has one counting symbol in it (a literal before
/// it goes in `number_prefix`); a label in a box (`label_box`, else a `hang` over 0: lib/pandoc/xdoc.lua label_width)
/// sets the label in a box that wide (typst), `\hbox to` it (LaTeX) or a tab to it (Word), which needs a left-aligned
/// heading unless the label has a line of its own (`label_line`).
pub fn validate_numbers(l: &Value, errs: &mut Vec<String>) {
    let Some(hs) = l.get("heading").and_then(Value::as_sequence) else {
        return;
    };
    for (i, h) in hs.iter().enumerate() {
        let Some(pat) = h.get("number") else { continue };
        let pat = pat.as_str().unwrap_or("");
        if pat.chars().filter(|c| "1IiAa".contains(*c)).count() != 1 {
            errs.push(format!(
                "layout.yaml: `heading[{i}].number` = {pat:?}: one counting symbol (1, I, i, A or a)"
            ));
        }
        let boxed = h.get("label_box").is_some()
            || h.get("hang").and_then(Value::as_f64).unwrap_or(0.0) > 0.0;
        let own_line = h.get("label_line").and_then(Value::as_bool) == Some(true);
        if boxed
            && !own_line
            && h.get("align")
                .and_then(Value::as_str)
                .is_some_and(|a| a != "left")
        {
            errs.push(format!(
                "layout.yaml: `heading[{i}].number` in a box needs a left-aligned heading"
            ));
        }
    }
}

/// The paper (layout.yaml `paper`: `letter`, the default, 612 x 792 pt, or `legal`, 612 x 1008 pt): its LaTeX geometry
/// option and its height in twips (the width is 8.5 in, 12240 twips, on both).
pub fn paper(l: &Value) -> Result<(&'static str, u32), String> {
    match l.get("paper").map(|p| p.as_str().unwrap_or("?")) {
        None | Some("letter") => Ok(("letterpaper", 15840)),
        Some("legal") => Ok(("legalpaper", 20160)),
        Some(p) => Err(format!("layout.yaml: `paper` = {p:?}: letter or legal")),
    }
}

/// A Lua literal of a YAML value (maps keep their order; null is nil).
pub fn lua(v: &Value, indent: usize) -> String {
    let pad = "  ".repeat(indent + 1);
    let end = "  ".repeat(indent);
    match v {
        Value::Null => "nil".into(),
        Value::Bool(b) => b.to_string(),
        Value::Number(n) => n.as_f64().map(fmt).unwrap_or_else(|| n.to_string()),
        Value::String(s) => lua_str(s),
        Value::Sequence(s) if s.is_empty() => "{}".into(),
        Value::Sequence(s) => {
            let items: Vec<String> = s
                .iter()
                .map(|x| format!("{pad}{},", lua(x, indent + 1)))
                .collect();
            format!("{{\n{}\n{end}}}", items.join("\n"))
        }
        Value::Mapping(m) if m.is_empty() => "{}".into(),
        Value::Mapping(m) => {
            let items: Vec<String> = m
                .iter()
                .filter(|(_, x)| !x.is_null())
                .map(|(k, x)| {
                    let k = k.as_str().unwrap_or("?");
                    format!("{pad}[{}] = {},", lua_str(k), lua(x, indent + 1))
                })
                .collect();
            format!("{{\n{}\n{end}}}", items.join("\n"))
        }
        Value::Tagged(t) => lua(&t.value, indent),
    }
}

fn lua_str(s: &str) -> String {
    let mut o = String::from("\"");
    for c in s.chars() {
        match c {
            '"' => o.push_str("\\\""),
            '\\' => o.push_str("\\\\"),
            '\n' => o.push_str("\\n"),
            c => o.push(c),
        }
    }
    o.push('"');
    o
}

/// The LaTeX packages that set the metrics of a typst face (docs/EVAL-LOOP.md, "Adopting the reference breaker",
/// step 0), and the face's ellipsis advance in em when it is known (\xd@ellipsis kerns three periods to it).
pub fn latex_face(face: &str) -> Result<(&'static str, Option<f64>), String> {
    match face {
        // Times New Roman and Liberation Serif: the ellipsis is 1000/1000 em, newtx's period 250
        "Times New Roman" | "Liberation Serif" | "TeX Gyre Termes" => {
            Ok(("\\usepackage{newtxtext,newtxmath}", Some(1.0)))
        }
        // EB Garamond: lining tabular figures (the vendored font's defaults; the package's are old-style and
        // proportional), its advances then the vendored font's but a regular T (latex_specials) and the ellipsis (tex.rs:
        // \\xd@glyph at its four advances)
        "EB Garamond" => Ok(("\\usepackage[lining,tabular]{ebgaramond}", None)),
        "Gelasio" => Ok(("\\usepackage{gelasio}", None)),
        // TeX Live's Type 1 Schola, with the advances of the vendored TeX Gyre Schola 2.609 where they differ
        // (lib/latex/xeschola.sty, which needs graphicx; lib/latex/xdoc.lua runs lib/latex/xeschola.lua: latex_glyphs);
        // the ellipsis is xeschola's glyph (\xd@ellipsis, tex.rs)
        // Arial (Fla. R. App. P. 9.045(b)) and its metric twin Liberation Sans: TeX Gyre Heros, a Helvetica clone, whose
        // advances (and Arial's) are Liberation Sans's in all four shapes, spaces included (measured: within 0.0002 em);
        // the ellipsis 1000/1000 em, the period 278
        "Liberation Sans" | "Arial" | "TeX Gyre Heros" => Ok((
            "\\usepackage{tgheros}\n\\renewcommand\\familydefault{\\sfdefault}",
            Some(1.0),
        )),
        // Bookman Old Style (Fla. R. App. P. 9.045(b)) as TeX Gyre Bonum: TeX Live's Type 1 tgbonum has the vendored
        // Bonum's advances in all four shapes (the printable ASCII, quotes, dashes, § and ¶ measured at 1000 pt: within
        // 0.0005 em); its \\textellipsis is three spaced periods (1.44 em), the font's glyph 1 em: \\xd@ellipsis
        "TeX Gyre Bonum" | "Bookman Old Style" => Ok(("\\usepackage{tgbonum}", Some(1.0))),
        // Courier New (W.D. and E.D. Wash. LCivR 10(d) allow a monospaced face) and its metric twin Liberation Mono, the
        // vendored face: TeX Gyre Cursor, a Courier clone of the same 0.6 em advance for every character in every shape
        // (Liberation Mono's is 1229/2048 em, 0.0001 em wider: a 6.4 in line at 14 pt holds the same 54 characters);
        // its ellipsis one character of 0.6 em, the period 0.6 em (fb-595.96)
        "Liberation Mono" | "Courier New" | "TeX Gyre Cursor" => Ok((
            "\\usepackage{tgcursor}\n\\renewcommand\\familydefault{\\ttdefault}",
            Some(0.6),
        )),
        "TeX Gyre Schola" | "Century Schoolbook" => Ok((
            "\\usepackage{tgschola}\n\\usepackage{graphicx}\n\\usepackage{xeschola} % lib/latex/xeschola.sty, inlined by fb render",
            None,
        )),
        f => Err(format!(
            "no LaTeX face for `{f}` (one face per template: newtx, tgschola, tgheros, tgbonum, ebgaramond, gelasio)"
        )),
    }
}

/// The glyph filter lib/latex/xdoc.lua runs for a face whose TeX Live advances differ from the vendored font's
/// (layout key `latex_glyphs` of the generated latex/xdoc.lua): Schola's (lib/latex/xeschola.lua).
pub fn latex_glyphs(face: &str) -> Option<&'static str> {
    match face {
        "TeX Gyre Schola" | "Century Schoolbook" => Some("schola"),
        _ => None,
    }
}

/// The characters whose TeX Live advance differs from the vendored font's and that lib/latex/xdoc.lua sets in a box of
/// the vendored advance (the generated latex/xdoc.lua's `latex_specials`: character -> code point, LaTeX, the regular,
/// bold, italic and bold italic advances in em; measured with typst and pdfLaTeX at 1000 pt); None for the faces that
/// need none (Times New Roman has lib/latex/xdoc.lua's own table).
pub fn latex_specials(face: &str) -> Option<Value> {
    let table: &[(&str, &str, &str, [f64; 4])] = match face {
        // ebgaramond's regular T is 0.667 em, the vendored font's 0.670
        "EB Garamond" => &[("T", "0054", "T", [0.67, 0.695, 0.622, 0.676])],
        _ => return None,
    };
    let mut m = serde_yaml::Mapping::new();
    for (c, hex, tex, adv) in table {
        let mut row: Vec<Value> = vec![(*hex).into(), (*tex).into()];
        row.extend(adv.iter().map(|a| Value::from(*a)));
        m.insert((*c).into(), Value::Sequence(row));
    }
    Some(Value::Mapping(m))
}

/// The advances (em) of a face's digit, comma, space and hyphen, which set the width of a page list in Word (the
/// generated docx/xdoc.lua's `face_advances`, lib/docx/xdoc.lua list_width), as typst measures the vendored font;
/// None for Times New Roman, lib/docx/xdoc.lua's own.
pub fn face_advances(face: &str) -> Option<[f64; 4]> {
    match face {
        "TeX Gyre Schola" | "Century Schoolbook" => Some([0.556, 0.278, 0.278, 0.333]),
        "Liberation Sans" | "Arial" | "TeX Gyre Heros" => Some([0.556, 0.278, 0.278, 0.333]),
        "TeX Gyre Bonum" | "Bookman Old Style" => Some([0.62, 0.32, 0.32, 0.4]),
        "Liberation Mono" | "Courier New" | "TeX Gyre Cursor" => Some([0.6, 0.6, 0.6, 0.6]),
        "EB Garamond" => Some([0.48, 0.23, 0.2, 0.274]),
        _ => None,
    }
}

/// The period's advance (em) of a face's LaTeX package: \\xd@ellipsis kerns three of them to the face's ellipsis.
pub fn latex_period(face: &str) -> f64 {
    match face {
        "Liberation Sans" | "Arial" | "TeX Gyre Heros" => 0.278,
        "TeX Gyre Bonum" | "Bookman Old Style" => 0.32,
        "Liberation Mono" | "Courier New" | "TeX Gyre Cursor" => 0.6,
        _ => 0.25,
    }
}

/// How much wider the LaTeX text block is than typst's (points): newtx sets a full line up to about 0.05 bp wider
/// than Times New Roman (+0.05/1000 em per character; docs/EVAL-LOOP.md, fb-595.54.9), which moved the break of a line
/// typst fills to within that (the Arkansas pilot: 0.05 pt to spare, 0.06 pt of drift).
pub fn latex_bias(face: &str) -> f64 {
    match face {
        "Times New Roman" | "Liberation Serif" | "TeX Gyre Termes" => 0.05,
        _ => 0.0,
    }
}

/// The LaTeX bias of a folder: its layout's `latex_bias` (points, measured for the folder when one of its lines ties
/// inside the face's window: the Wisconsin answering brief's 0.06, fb-595.54.16), else the face's (latex_bias).
pub fn folder_latex_bias(l: &Value, face: &str) -> f64 {
    l.get("latex_bias")
        .and_then(Value::as_f64)
        .unwrap_or_else(|| latex_bias(face))
}

/// The layout Word sets: `margin.right` wider by the folder's measured `docx_bias` (points, whole twips), the key
/// itself dropped. LibreOffice rounds each run of text to its layout units, so a line of many runs (italics) that typst
/// overflows by a tenth of a point may still fit there (the Wisconsin amicus brief's 0.1, fb-595.54.16; none by
/// default).
pub fn word_layout(l: &Value) -> Result<Value, String> {
    let bias = num(l, "docx_bias", Some(0.0))?;
    let mut ld = l.clone();
    if let Some(m) = ld.as_mapping_mut() {
        m.remove("docx_bias");
    }
    if bias != 0.0 {
        let right = num(l, "margin.right", None)?;
        if let Some(Value::Mapping(mg)) = ld.get_mut("margin") {
            mg.insert("right".into(), (right + bias).into());
        }
    }
    Ok(ld)
}

/// The page number's line: its pitch and baseline below the text (typst: footer-descent 30 % of the bottom margin,
/// or the layout's `page_number.descent`, the number in a line box of `page_number.pitch`, the single pitch by
/// default), and Word's footer distance (from the page foot to the bottom of that box).
pub fn footer(l: &Value) -> Result<(f64, f64, f64), String> {
    let mb = num(l, "margin.bottom", None)?;
    let ps = num(l, "page_number.pitch", Some(num(l, "pitch.single", None)?))?;
    // `page_number.foot` (fb-595.96): the last line's box ends that far above the page's foot (its baseline a fifth of
    // the pitch above that), the footer growing upward as Word's does; its distance is Word's footer distance
    if let Some(foot) = footed(l)? {
        return Ok((ps, mb - foot - 0.2 * ps, foot));
    }
    let descent = num(l, "page_number.descent", Some(0.3 * mb))?;
    let skip = descent + 0.8 * ps;
    let dist = mb - descent - ps;
    Ok((ps, skip, dist))
}

/// The layout's `page_number.foot` (points), when it anchors the footer at its foot.
pub fn footed(l: &Value) -> Result<Option<f64>, String> {
    match l.get("page_number").and_then(|p| p.get("foot")) {
        None => Ok(None),
        Some(_) => num(l, "page_number.foot", None).map(Some),
    }
}

/// The generated files of a folder whose template sets `face` and whose layout is `l`.
pub fn generate(l: &Value, face: &str) -> Result<Files, String> {
    let mut errs = Vec::new();
    validate(l, "", &mut errs);
    validate_numbers(l, &mut errs);
    if let Err(e) = paper(l) {
        errs.push(e);
    }
    if let Err(e) = super::tex::pleading(l) {
        errs.push(e);
    }
    if !errs.is_empty() {
        return Err(errs.join("\n"));
    }
    // Word measures a page list with the face's advances (Times New Roman's unless given), its right margin wider by
    // the folder's docx_bias (word_layout)
    let ld = word_layout(l)?;
    let mut wl = ld.clone();
    if let (Some(m), Some(a)) = (wl.as_mapping_mut(), face_advances(face)) {
        let adv: serde_yaml::Mapping = ["digit", "comma", "space", "hyphen"]
            .iter()
            .zip(a)
            .map(|(k, v)| (Value::from(*k), Value::from(v)))
            .collect();
        m.insert("face_advances".into(), Value::Mapping(adv));
    }
    let spec = lua(&wl, 0);
    // the LaTeX text block is wider by the face's measured bias (latex_bias), and lib/latex/xdoc.lua must know it,
    // and the glyph filter of the face (latex_glyphs)
    let mut lt = l.clone();
    if let Some(m) = lt.as_mapping_mut() {
        m.insert("latex_bias".into(), folder_latex_bias(l, face).into());
        if let Some(g) = latex_glyphs(face) {
            m.insert("latex_glyphs".into(), g.into());
        }
        if let Some(s) = latex_specials(face) {
            m.insert("latex_specials".into(), s);
        }
    }
    let latex_spec = lua(&lt, 0);
    let latex_lua = format!(
        "-- {HEAD}\n-- The shared document model in LaTeX: lib/latex/xdoc.lua sets this layout.\nreturn require(\"latex.xdoc\")({latex_spec})\n"
    );
    let docx_lua = format!(
        "-- {HEAD}\n-- The shared document model in Word: lib/docx/xdoc.lua sets this layout.\nreturn require(\"docx.xdoc\")({spec})\n"
    );
    Ok(vec![
        ("latex/template.tex".into(), super::tex::template(l, face)?),
        ("latex/xdoc.lua".into(), latex_lua),
        (
            "docx/reference.xml".into(),
            super::word::reference(&ld, face)?,
        ),
        ("docx/xdoc.lua".into(), docx_lua),
    ])
}

/// The generated files of the doc folder `dir`.
pub fn for_folder(dir: &Path) -> Res<Files> {
    let bad = |m: String| fail(1, format!("fb engines gen: {}: {m}", dir.display()));
    let layout = dir.join("typst/layout.yaml");
    let text = std::fs::read_to_string(&layout).map_err(|e| {
        bad(format!(
            "{}: {e} (not on the shared document model)",
            layout.display()
        ))
    })?;
    let l: Value = serde_yaml::from_str(&text).map_err(|e| bad(format!("layout.yaml: {e}")))?;
    let root =
        super::base::root_of(dir).ok_or_else(|| bad("no repo root (data/index.json)".into()))?;
    let l = super::base::resolve(l, &super::base::reader(&root)).map_err(bad)?;
    let face = crate::typstface::face(dir)
        .ok_or_else(|| bad("the typst template names no face (#let font-family = ..)".into()))?;
    if super::engines_of(dir).contains(&"docx-sh") {
        return Err(bad(
            "has docx/*.sh (fb-595.68 step 2 owns it): not generated".into(),
        ));
    }
    generate(&l, &face).map_err(bad)
}

pub fn main(args: &[String]) -> Res<std::process::ExitCode> {
    let check = args.iter().any(|a| a == "--check");
    let dirs: Vec<&String> = args.iter().filter(|a| !a.starts_with("--")).collect();
    if dirs.is_empty() {
        return Err(fail(2, "usage: fb engines gen <doc-folder>... [--check]"));
    }
    let mut stale = 0;
    for d in dirs {
        let dir = Path::new(d);
        for (rel, text) in for_folder(dir)? {
            let p = dir.join(&rel);
            let old = std::fs::read_to_string(&p).ok();
            if old.as_deref() == Some(text.as_str()) {
                continue;
            }
            if check {
                println!("STALE {}", p.display());
                stale += 1;
                continue;
            }
            if let Some(parent) = p.parent() {
                std::fs::create_dir_all(parent)
                    .map_err(|e| fail(2, format!("fb engines gen: {}: {e}", parent.display())))?;
            }
            std::fs::write(&p, &text)
                .map_err(|e| fail(2, format!("fb engines gen: {}: {e}", p.display())))?;
            println!("wrote {}", p.display());
        }
    }
    Ok(if stale > 0 {
        std::process::ExitCode::from(1)
    } else {
        std::process::ExitCode::SUCCESS
    })
}

/// Whether a page-number text is a running footer (layout.yaml `page_number.text` that names a frontmatter field
/// besides `{page}` and `{pages}`, or holds a "<br>"): its lines set by the shared model from the sample
/// (lib/typst/xdoc.typ footer-lines, lib/pandoc/xdoc.lua footer_lines), not by the generated template.
pub fn is_running(text: &str) -> bool {
    if text.contains("<br>") || text.contains("<tab>") {
        return true;
    }
    let mut rest = text;
    while let Some(a) = rest.find('{') {
        let tail = &rest[a + 1..];
        match tail.find(['{', '}']) {
            Some(b) if tail.as_bytes()[b] == b'}' => {
                if !matches!(&tail[..b], "" | "page" | "pages") {
                    return true;
                }
                rest = &tail[b + 1..];
            }
            Some(b) => rest = &tail[b..],
            None => break,
        }
    }
    false
}

/// The number of lines of the page-number footer: a running footer's lines, else one.
pub fn footer_lines(l: &Value) -> usize {
    match l
        .get("page_number")
        .and_then(|p| p.get("text"))
        .and_then(Value::as_str)
    {
        Some(t) if is_running(t) => t.matches("<br>").count() + 1,
        _ => 1,
    }
}
