//! `data/courts.tsv`: one line per court of data/index.json, in index order, for callers that select a court
//! without a JSON parser (tools/court.bend, fb-595.103). Written by `fb tracker`, checked by `fb tracker --check`.
//! Columns, tab-separated: alias, folder path, name, verified date (YYYY-MM-DD or empty), doc types (comma list of
//! the court folder's doc-type subfolders: a subfolder with `typst/` or `usage/` that is not itself a court),
//! legacy aliases (comma list, from index.json `legacy_aliases`).
//! The verified date is the newest ISO date that follows the word "verified" (any case) on one line of the
//! court's own `rules.md`: rules.md headers say "Verified against primary sources on 2026-10-17", source lists say
//! "verified 2026-10-17", and the newest is when anyone last re-checked the court's rules.
use crate::{fail, Res};
use serde_json::Value;
use std::path::Path;

pub const PATH: &str = "data/courts.tsv";

const HEADER: &str = "# GENERATED by fb tracker (fb-595.103). Do not edit. alias\tpath\tname\tverified\tdoctypes\tlegacy\n";

/// The ISO dates (YYYY-MM-DD) in `s`, in order.
fn iso_dates(s: &str) -> Vec<&str> {
    let b = s.as_bytes();
    let shape = |w: &[u8]| {
        w.iter().enumerate().all(|(i, c)| match i {
            4 | 7 => *c == b'-',
            _ => c.is_ascii_digit(),
        })
    };
    (0..b.len().saturating_sub(9))
        .filter(|&i| shape(&b[i..i + 10]))
        .filter(|&i| i == 0 || !b[i - 1].is_ascii_digit())
        .filter(|&i| b.get(i + 10).is_none_or(|c| !c.is_ascii_digit()))
        .map(|i| &s[i..i + 10])
        .collect()
}

/// The newest date that follows "verified" on a line of `rules`, if any.
pub fn verified(rules: &str) -> Option<String> {
    rules
        .lines()
        .filter_map(|l| {
            let at = l.to_ascii_lowercase().find("verified")?;
            Some(iso_dates(&l[at..]).into_iter().map(str::to_string).collect::<Vec<_>>())
        })
        .flatten()
        .max()
}

/// The doc-type subfolders of a court folder, sorted.
fn doctypes(dir: &Path) -> Vec<String> {
    let mut v: Vec<String> = std::fs::read_dir(dir)
        .into_iter()
        .flatten()
        .flatten()
        .map(|e| e.path())
        .filter(|p| p.is_dir() && !p.join("court.json").is_file())
        .filter(|p| p.join("typst").is_dir() || p.join("usage").is_dir())
        .filter_map(|p| p.file_name()?.to_str().map(str::to_string))
        .filter(|n| !["typst", "latex", "docx", "usage", "reviews"].contains(&n.as_str()))
        .collect();
    v.sort();
    v
}

/// The whole file, from the index and the court folders under `root`.
pub fn tsv(root: &Path, index: &Value) -> String {
    let field = |c: &Value, k: &str| c[k].as_str().unwrap_or("").replace(['\t', '\n'], " ");
    let rows: String = index["courts"]
        .as_object()
        .into_iter()
        .flatten()
        .map(|(alias, c)| {
            let path = field(c, "path");
            let dir = root.join(&path);
            let date = std::fs::read_to_string(dir.join("rules.md"))
                .ok()
                .and_then(|r| verified(&r))
                .unwrap_or_default();
            let legacy: Vec<&str> = index["legacy_aliases"]
                .as_object()
                .into_iter()
                .flatten()
                .filter(|(_, to)| to.as_str() == Some(alias))
                .map(|(from, _)| from.as_str())
                .collect();
            format!(
                "{alias}\t{path}\t{}\t{date}\t{}\t{}\n",
                field(c, "name"),
                doctypes(&dir).join(","),
                legacy.join(",")
            )
        })
        .collect();
    format!("{HEADER}{rows}")
}

/// `data/courts.tsv` as it should be now.
pub fn expected(root: &Path) -> Res<String> {
    let p = root.join("data/index.json");
    let t = std::fs::read_to_string(&p).map_err(|e| fail(2, format!("{}: {e}", p.display())))?;
    let index: Value =
        serde_json::from_str(&t).map_err(|e| fail(2, format!("{}: {e}", p.display())))?;
    Ok(tsv(root, &index))
}

/// `fb courts`: print `data/courts.tsv` as it should be now (`fb tracker` writes it).
pub fn main(args: &[String]) -> Res<std::process::ExitCode> {
    match args {
        [] => {
            print!("{}", expected(&crate::repo_root()?)?);
            Ok(std::process::ExitCode::SUCCESS)
        }
        _ => Err(fail(2, "usage: fb courts")),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn dates_are_whole_iso_dates() {
        assert_eq!(iso_dates("on 2026-10-17, and 2025-01-02."), ["2026-10-17", "2025-01-02"]);
        assert!(iso_dates("12026-10-17 2026-10-170 2026/10/17 26-10-17").is_empty());
        assert_eq!(iso_dates("2026-10-17"), ["2026-10-17"]);
    }

    #[test]
    fn verified_is_the_newest_date_after_the_word() {
        let r = "Scope. Verified against primary sources on 2026-10-17. Re-check yearly.\n\
                 - FRAP 32 (amended 2027-12-01), verified 2026-11-02\n\
                 - Effective 2028-01-01 (not verified)\n\
                 Last edited 2029-01-01\n";
        assert_eq!(verified(r).as_deref(), Some("2026-11-02"));
        assert_eq!(verified("Updated 2026-10-17\n"), None);
        assert_eq!(verified("VERIFIED on 2025-03-04\n").as_deref(), Some("2025-03-04"));
    }

    #[test]
    fn tsv_rows_follow_the_index() {
        let tmp = crate::proc::TempDir::new("courts").unwrap();
        let root = tmp.path();
        let c = root.join("courts/a");
        std::fs::create_dir_all(c.join("motion-brief/typst")).unwrap();
        std::fs::create_dir_all(c.join("typst")).unwrap();
        std::fs::create_dir_all(c.join("notes")).unwrap();
        std::fs::create_dir_all(c.join("sub/usage")).unwrap();
        std::fs::write(c.join("sub/court.json"), "{}").unwrap();
        std::fs::write(c.join("rules.md"), "Verified against primary sources on 2026-10-17.\n").unwrap();
        let ix = serde_json::json!({
            "courts": {"a": {"path": "courts/a", "name": "Court\tA"}, "b": {"path": "courts/b", "name": "B"}},
            "legacy_aliases": {"old": "a"}
        });
        let t = tsv(root, &ix);
        let rows: Vec<&str> = t.lines().skip(1).collect();
        assert_eq!(
            rows,
            ["a\tcourts/a\tCourt A\t2026-10-17\tmotion-brief\told", "b\tcourts/b\tB\t\t\t"]
        );
    }
}
