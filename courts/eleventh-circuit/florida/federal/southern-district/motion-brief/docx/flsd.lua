-- Motion to dismiss with incorporated memorandum, S.D. Fla. (flsd), DOCX engine (docs/DOCX.md): the markdown
-- contract -> Word on reference.docx, in the form of typst/flsd-motion-brief.typ (S.D. Fla. L.R. 5.1(a), 5.2).
-- The caption, the signature block, the certificate of service and the spacing blocks are paragraphs in the
-- custom styles of reference.docx (Centered, CaptionLine, SigLine, GapLarge, ...). The body is unnumbered (a
-- motion is not a pleading); footnotes are Word footnotes. The page number comes from the reference's footer.

local function stringify(v)
  if v == nil then return "" end
  return pandoc.utils.stringify(v)
end

-- a paragraph in a custom paragraph style of reference.docx
local function para(style, inlines)
  return pandoc.Div({ pandoc.Para(inlines) }, pandoc.Attr("", {}, { ["custom-style"] = style }))
end

-- an empty paragraph of exact height (the typst v() gaps)
local function gap(style)
  return pandoc.RawBlock("openxml", '<w:p><w:pPr><w:pStyle w:val="' .. style .. '"/></w:pPr></w:p>')
end

local function bold(text)
  return pandoc.Strong({ pandoc.Str(text) })
end

function Pandoc(doc)
  local m = doc.meta
  local out = {}
  local function add(b) out[#out + 1] = b end

  -- caption: court (L.R. 5.1(a)(5)(A)), division, docket line (B), style at the left (C), title (D)
  add(para("Centered", { bold("UNITED STATES DISTRICT COURT") }))
  add(para("Centered", { bold("SOUTHERN DISTRICT OF FLORIDA") }))
  if m.division then
    add(para("Centered", { bold(stringify(m.division):upper()) }))
  end
  add(gap("GapLarge"))
  add(para("Centered", { pandoc.Str("CIVIL CASE NO. " .. stringify(m.case_number)) }))
  add(gap("GapLarge"))
  local rows = {}
  for k, p in ipairs(m.caption.parties) do
    if k > 1 then rows[#rows + 1] = "v." end
    for _, n in ipairs(p.names) do rows[#rows + 1] = stringify(n) end
    rows[#rows + 1] = stringify(p.designation)
  end
  rows[#rows + 1] = "/"
  for _, r in ipairs(rows) do add(para("CaptionLine", { pandoc.Str(r) })) end
  add(gap("GapLarge"))
  add(para("Centered", { bold(stringify(m.title):upper()) }))
  add(gap("GapLarge"))

  -- body: headings, lists, footnotes and paragraphs as written (no paragraph numbers)
  for _, b in ipairs(doc.blocks) do add(b) end

  -- signature block (L.R. 5.1(a)(6)), kept together as in the typst template
  add(gap("GapSmall"))
  add(para("SingleKeep", { pandoc.Str("Dated: " .. stringify(m.date)) }))
  add(gap("GapSmall"))
  add(para("SigLine", { pandoc.Str("Respectfully submitted,") }))
  add(gap("GapSmall"))
  add(para("SigLine", { pandoc.Str("By: s/ " .. stringify(m.signature.signer)) }))
  for i, l in ipairs(m.signature.lines) do
    -- the last line does not keep with what follows: the certificate is its own block (as in the typst template)
    add(para(i == #m.signature.lines and "SigLast" or "SigLine", { pandoc.Str(stringify(l)) }))
  end

  -- certificate of service (L.R. 5.2), kept together as in the typst template
  if m.service then
    local s = m.service
    add(gap("GapPlain"))
    add(para("CenteredKeep", { bold("CERTIFICATE OF SERVICE") }))
    add(para("BodyKeep", { pandoc.Str("I HEREBY CERTIFY that on this " .. stringify(s.date) .. ", I electronically filed the foregoing document with the Clerk of the Court using CM/ECF. I also certify that the foregoing document is being served this day on all counsel of record in the manner specified, either via transmission of Notices of Electronic Filing generated by CM/ECF or in some other authorized manner for those counsel or parties who are not authorized to receive electronically Notices of Electronic Filing.") }))
    add(gap("GapSmall"))
    add(para("SigLine", { pandoc.Str("s/" .. stringify(s.signer)) }))
    add(para("SigLine", { pandoc.Str(stringify(s.signer)) }))
    add(gap("GapSmall"))
    add(para("SingleKeep", { bold("SERVICE LIST") }))
    for i, l in ipairs(s.list) do
      add(para(i == #s.list and "Single" or "SingleKeep", { pandoc.Str(stringify(l)) }))
    end
  end

  doc.blocks = out
  doc.meta = {}
  return doc
end
