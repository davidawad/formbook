local M = {}

-- The advance of one character in style s ("r", "b", "i", "bi") at size pt.
local function adv(ch, s, size)
  return (W[s][ch] or 500) * size / 1000
end

-- Break opportunities as typst and LibreOffice take them (Unicode line breaking): after a space, after a hyphen not
-- followed by a digit, before and after an em dash, after an en dash, after a slash before a letter.
local function pieces(chars)
  local out, cur = {}, {}
  local function flush() if #cur > 0 then out[#out + 1] = cur; cur = {} end end
  for k, c in ipairs(chars) do
    local nxt = chars[k + 1] and chars[k + 1].ch or ""
    if c.ch == "\u{2014}" then flush() end
    cur[#cur + 1] = c
    if c.ch == " " or c.ch == "\u{2014}" or c.ch == "\u{2013}"
      or (c.ch == "-" and not nxt:match("^%d")) or (c.ch == "/" and nxt:match("^%a")) then
      flush()
    end
  end
  flush()
  return out
end

-- Lines of runs {{text, style}, ...} first fit in width pt at size pt. A trailing space hangs in the margin.
function M.lines(runs, width, size)
  local chars = {}
  for _, r in ipairs(runs) do
    for _, ch in utf8.codes(r[1]) do chars[#chars + 1] = { ch = utf8.char(ch), s = r[2] } end
  end
  if #chars == 0 then return 1 end
  local n, x = 1, 0
  for _, p in ipairs(pieces(chars)) do
    local w, ws = 0, 0
    for _, c in ipairs(p) do w = w + adv(c.ch, c.s, size) end
    ws = w
    if p[#p].ch == " " then ws = w - adv(" ", p[#p].s, size) end
    if x > 0 and x + ws > width + 0.01 then
      n = n + 1
      x = w
    else
      x = x + w
    end
  end
  return n
end

-- Pandoc inlines as runs: emphasis italic, strong bold; `bold` sets the whole block bold.
function M.runs(inlines, bold)
  local out = {}
  local function walk(list, b, i)
    for _, el in ipairs(list) do
      local s = (b and i) and "bi" or b and "b" or i and "i" or "r"
      if el.t == "Str" then out[#out + 1] = { el.text, s }
      elseif el.t == "Space" or el.t == "SoftBreak" or el.t == "LineBreak" then out[#out + 1] = { " ", s }
      elseif el.t == "Emph" then walk(el.content, b, not i)
      elseif el.t == "Strong" then walk(el.content, true, i)
      elseif el.t == "Quoted" then
        local q = el.quotetype == "DoubleQuote" and { "\u{201C}", "\u{201D}" } or { "\u{2018}", "\u{2019}" }
        out[#out + 1] = { q[1], s }; walk(el.content, b, i); out[#out + 1] = { q[2], s }
      elseif el.content then walk(el.content, b, i)
      else out[#out + 1] = { pandoc.utils.stringify(el), s } end
    end
  end
  walk(inlines, bold or false, false)
  return out
end

return M
